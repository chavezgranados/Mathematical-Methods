import numpy as np
import matplotlib.pyplot as plt

def cobb_douglas(K, L, alpha=0.3, A=1):
  """
  Cobb-Douglas production function.
  Args:
    K: Capital input.
    L: Labor input.
    alpha: Capital share parameter (0 < alpha < 1).
    A: Total factor productivity.
  Returns:
    The output produced.
  """
  return A * (K**alpha) * (L**(1 - alpha))

K_vals = np.linspace(1, 10, 100)  # Range capital
L_vals = np.linspace(1, 10, 100)  # Range labor
K, L = np.meshgrid(K_vals, L_vals)
Y = cobb_douglas(K, L)

fig = plt.figure(figsize=(10, 8))
ax = fig.add_subplot(111, projection='3d')
ax.plot_surface(K, L, Y, cmap='viridis')

ax.set_xlabel("K")
ax.set_ylabel("L")
ax.set_zlabel("Y")
ax.set_title("Cobb-Douglas Function")
plt.show()

# Ejemplo 1:
capital = 5
labor = 7
output = cobb_douglas(capital, labor)
print(f"Output with capital {capital} and labor {labor}: {output}")

