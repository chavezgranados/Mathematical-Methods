import plotly.graph_objects as go
import numpy as np

def cobb_douglas(K, L, A, alpha, beta):
    return A * (K**alpha) * (L**beta)

k_range = np.linspace(0.1, 5, 50)
l_range = np.linspace(0.1, 5, 50)
K, L = np.meshgrid(k_range, l_range)
A = 1
alpha = 0.3
beta = 0.7

Z = cobb_douglas(K, L, A, alpha, beta)
fig = go.Figure(data=[go.Surface(z=Z, x=K, y=L)])
fig.update_layout(
    title='Función de Producción Cobb-Douglas', width=800, height=600,
    scene=dict(
        xaxis_title='K',
        yaxis_title='L',
        zaxis_title='Y',
        camera=dict(
            eye=dict(x=1.25, y=1.25, z=1.25) # Posición inicial de la cámara
        )
    )
)
fig.show()