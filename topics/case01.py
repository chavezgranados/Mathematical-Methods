import numpy as np
import matplotlib.pyplot as plt
from ipywidgets import interact, fixed

def cobb_douglas_interactive(K, L, alpha=0.3, A=1):
  """
  Interactive Cobb-Douglas production function.
  """
  Y = cobb_douglas(K, L, alpha, A)
  print(f"Output with capital {K} and labor {L}: {Y}")

  fig = plt.figure(figsize=(10, 8))
  ax = fig.add_subplot(111, projection='3d')
  K_vals = np.linspace(1, 10, 100)
  L_vals = np.linspace(1, 10, 100)
  K_grid, L_grid = np.meshgrid(K_vals, L_vals)
  Y_grid = cobb_douglas(K_grid, L_grid, alpha, A)
  ax.plot_surface(K_grid, L_grid, Y_grid, cmap='viridis')

  ax.set_xlabel("K")
  ax.set_ylabel("L")
  ax.set_zlabel("Y")
  ax.set_title("Cobb-Douglas Function")
  plt.show()

interact(cobb_douglas_interactive, K=(1, 10, 0.1), L=(1, 10, 0.1), alpha=(0.1, 0.9, 0.1), A=(0.5, 2, 0.1));

